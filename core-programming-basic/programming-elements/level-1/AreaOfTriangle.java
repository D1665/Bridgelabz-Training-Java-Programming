public class AreaOfTriangle {
    public static void main(String[] args) {
        double base = 10.0; // Base of the triangle
        double height = 5.0; // Height of the triangle

        double area = (base * height) / 2; // Area formula: (base * height) / 2

        System.out.println("The area of the triangle with base " + base + " and height " + height + " is: " + area);
    }
}
